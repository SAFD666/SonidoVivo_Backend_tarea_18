-- =====================================================================
-- Sonido Vivo - Modelo de datos (REFERENCIA, PostgreSQL), adaptado al frontend SonidoVivo-main
-- Las tablas las crea Hibernate automáticamente al iniciar el backend
-- (spring.jpa.hibernate.ddl-auto=update) a partir de las clases del paquete model.
-- Este archivo muestra el resultado equivalente en SQL para explicar el modelo.
-- Si prefieren crearlas a mano:  psql -h ENDPOINT_DEL_RDS -U postgres -d sonido_vivo -f db/01_modelo_referencia.sql
--
-- Correspondencia con el frontend (src/data):
--   usuarios.js   -> rol + usuario         (rol: Administrador | Vendedor | Cliente)
-- =====================================================================

CREATE TABLE IF NOT EXISTS rol (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30)  NOT NULL,                 -- ADMINISTRADOR | VENDEDOR | CLIENTE (la API los muestra como "Administrador"...)
    descripcion  VARCHAR(150),
    CONSTRAINT uk_rol_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS usuario (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(100) NOT NULL,
    correo            VARCHAR(120) NOT NULL,
    password_hash     VARCHAR(100) NOT NULL,            -- hash BCrypt, nunca la contraseña
    direccion         VARCHAR(200),
    activo            BOOLEAN      NOT NULL DEFAULT TRUE, -- eliminar = desactivar
    rol_id            BIGINT       NOT NULL,
    fecha_creacion    TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol (id)
);
